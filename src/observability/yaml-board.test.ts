import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { compileExplorerYaml, compileSql, snapshotYaml } from './yaml-board';
import { compileNativeChart } from './yaml-chart';
const yaml = readFileSync('charts/observability.yml', 'utf8');
const board = compileExplorerYaml(yaml);
assert.equal(board.charts.length, 8);
const waterfall = board.charts.find(c => c.id === 'waterfall')!;
assert.equal(waterfall.definition.type, 'bar');
assert.equal(waterfall.definition.y_start, 'start_ms');
const compiled = compileSql("SELECT {{ term }} FROM {{ ref('logs') }} -- {{ ignored }}", {term: "'; DROP TABLE logs; --"}, {logs: 'telemetry.logs'});
assert.equal(compiled.sql, 'SELECT ? FROM "telemetry"."logs" -- {{ ignored }}');
assert.deepEqual(compiled.params, ["'; DROP TABLE logs; --"]);
assert.throws(() => compileSql("SELECT '{{ term }}'", {term: 'x'}), /unquoted/);
assert.throws(() => compileSql('SELECT {{ absent }}', {}), /Unknown variable/);
const snapshot = compileExplorerYaml(snapshotYaml(yaml, {trace_id: 'another', threshold: 123}, true));
assert.equal(snapshot.variables.trace_id, 'another');
assert.equal(snapshot.variables.threshold, 123);
const renamed = compileExplorerYaml(yaml.replaceAll('waterfall:', 'renamed_trace:').replace(/- waterfall\b/g, '- renamed_trace'));
assert.equal(renamed.charts.find(c => c.id === 'renamed_trace')?.definition.y_start, 'start_ms');
const plan = compileNativeChart(waterfall.definition, [{trace_id:'t',span_id:'s',start_ns:'1000',trace_origin_ns:'1000',name:'label',service:'api',start_ms:0,end_ms:2}], {}, board.variables);
assert.equal(plan.config.plugin, 'Trace Waterfall');
assert.equal((plan.config.plugin_config as Record<string, unknown>)?.startColumn, 'start_ms');
console.log('YAML explorer: schema, all charts, SQL binding, snapshots, renamed IDs and waterfall channels passed');
