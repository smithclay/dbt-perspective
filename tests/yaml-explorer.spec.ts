import { test, expect } from '@playwright/test';
import { parse, stringify } from 'yaml';
import { compileExplorerYaml } from '../src/observability/yaml-board';
test('every explorer chart comes from editable, downloadable dbt YAML', async ({ page }) => {
  await page.goto('./observability.html');
  await expect(page.locator('#loader-status')).toContainText('Ready', {timeout:60000});
  const editor = page.locator('#explorer-yaml');
  const original = await editor.inputValue();
  expect(compileExplorerYaml(original).charts).toHaveLength(8);
  const board = parse(original);
  board.charts.renamed_trace = board.charts.waterfall;
  delete board.charts.waterfall;
  board.charts.renamed_trace.title = 'YAML authored trace';
  board.queries.trace_spans = board.queries.trace_spans.replace('SELECT *,', "SELECT * EXCLUDE(name), 'Edited ' || name AS name,");
  board.rows = ['renamed_trace', 'details'];
  await editor.fill(stringify(board));
  await page.locator('#apply-yaml').click();
  await expect(page.locator('#loader-status')).toContainText('Ready');
  await expect(page.locator('#observability-root perspective-viewer')).toHaveCount(2);
  await expect(page.locator('section[data-chart-id="renamed_trace"] > h2')).toHaveText('YAML authored trace');
  await expect(page.locator('.trace-summary')).toContainText('6 spans');
  const names = await page.locator('perspective-viewer[data-chart-id="renamed_trace"]').evaluate(async (viewer: any) => (await (await viewer.getView()).to_json()).map((r:any)=>r.name));
  expect(names.every((name:string)=>name.startsWith('Edited '))).toBe(true);
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#download-yaml').click();
  const download = await downloadPromise;
  const path = await download.path();
  const {readFileSync} = await import('node:fs');
  const saved = readFileSync(path!, 'utf8');
  expect(compileExplorerYaml(saved).charts.map(c=>c.id)).toEqual(['renamed_trace','details']);
  await editor.fill('charts: {bad: {type: invented}}');
  await page.locator('#apply-yaml').click();
  await expect(page.locator('#loader-status')).toHaveClass('error');
  await expect(page.locator('#observability-root perspective-viewer')).toHaveCount(2);
  await page.locator('#yaml-file').setInputFiles({name:'roundtrip.yml',mimeType:'application/yaml',buffer:Buffer.from(saved)});
  await expect(page.locator('#loader-status')).toContainText('Ready');
  await expect(page.locator('.trace-summary')).toContainText('6 spans');
});
